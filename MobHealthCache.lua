--[[
    MobHealthCache

    Since UnitHealthMax is secret, we cannot access fresh mob health in combat.
    This cache estimates and stores mob health for use by EstimateTargetMaxHealth().
    Estimates are derived from damage meter segments matched to recently targeted mobs.

    This uses a tiered cache. The most specific lookup we can do is by level, classification, power type, and zone. If
    that fails we fall back to increasingly less specific caches. If no cached value is found we use a global per-level
    estimate. We write to the caches after a combat session ends, using the damage meter output to estimate max health.
    Each cache level stores a decaying average of the last few writes to that level.

    This is of debatable precision but it's the best I can do with what the secretvalue API allows.
--]]

local addon = LibStub("AceAddon-3.0"):GetAddon("Sundered")
local mobHealthCache = addon:NewModule("MobHealthCache", "AceEvent-3.0")
SunderedMobHealthCache = SunderedMobHealthCache or {}
local targetSnapshots = {}

-- Restore cache branches if saved data is incomplete or was created by an older addon version.
local function ensureHealthCache()
    SunderedMobHealthCache.byLevelClassification = SunderedMobHealthCache.byLevelClassification or {}
    SunderedMobHealthCache.byLevelClassificationPowerType =
        SunderedMobHealthCache.byLevelClassificationPowerType or {}
    SunderedMobHealthCache.byLevelClassificationPowerTypeZone =
        SunderedMobHealthCache.byLevelClassificationPowerTypeZone or {}
end

-- Approximate maximum health for normal creatures by level.
local approximateMaxHealthByLevel = {
      44,   53,   64,   76,   89,  103,  119,  137,  156,  176,
     197,  219,  241,  264,  288,  290,  312,  338,  366,  397,
     430,  464,  501,  540,  581,  624,  669,  716,  765,  815,
     827,  830,  868,  915,  968, 1025, 1085, 1148, 1216, 1288,
    1363, 1444, 1529, 1619, 1714, 1835, 1962, 2095, 2234, 2367,
    2507, 2654, 2808, 2971, 3141, 3321, 3510, 3709, 3918, 4137,
    4367, 4609, 4863,
}

-- Health scaling estimate for elites, rares, etc. Not very accurate.
local approximateHealthMultiplierByClassification = {
    normal = 1,
    trivial = 1,
    minus = 0.5,
    rare = 1.5,
    elite = 2,
    rareelite = 3,
    worldboss = 1000,
}

-- Update a cached health value with a new health sample
local function updateAverage(cache, key, sample)
    -- We treat cache entries as expected values for a class of mobs, not exact health values for specific mobs.
    -- This is unfortunate, but required since we cannot read the exact max health values in combat or index using a
    -- name, creature ID or other more precise identifying information.
    local average = cache[key]
    if average then
        -- The smaller the value, the less the new sample will affect the average.
        local healthEstimateSmoothing = 0.05
        average = average * (1 - healthEstimateSmoothing) + sample * healthEstimateSmoothing
    else
        average = sample
    end
    cache[key] = average
end

-- Make a nested branch available for a more specific cache.
local function getCacheTable(cache, key)
    local value = cache[key]
    if not value then
        value = {}
        cache[key] = value
    end
    return value
end

-- Keep every level of specificity learning from each health sample.
local function updateHealthCaches(cache, level, classification, powerType, zone, sample)
    updateAverage(
        getCacheTable(getCacheTable(cache, "byLevelClassification"), level),
        classification, sample
    )
    updateAverage(
        getCacheTable(
            getCacheTable(getCacheTable(cache, "byLevelClassificationPowerType"), level),
            classification
        ),
        powerType, sample
    )
    updateAverage(
        getCacheTable(
            getCacheTable(
                getCacheTable(getCacheTable(cache, "byLevelClassificationPowerTypeZone"), level),
                classification
            ),
            powerType
        ),
        zone, sample
    )
end

ensureHealthCache()

-- Estimate the expected overkill damage for a given level.
local function estimateOverkillDamage(level)
    -- This is a fairly arbitrary heuristic dervied from a level-appropriate green 1H weapon, as generated by ol'
    -- Slopsy and tweaked by me. I didn't compute this myself. It is not accurate. It is probably better than nothing.
    local overkillTable = {
         5,   7,   8,   9,  11,  12,  14,  16,  17,  20,
        22,  24,  27,  29,  32,  35,  37,  40,  43,  46,
        50,  53,  56,  60,  65,  68,  72,  76,  81,  85,
        90,  96, 101, 106, 111, 118, 123, 130, 135, 141,
       146, 151, 156, 161, 166, 171, 176, 181, 186, 190,
       196, 200, 205, 210, 215, 220, 225, 230, 234, 240,
    }
    return overkillTable[level] or 0
end

-- Called on player target changing. Attempt to snapshot any target data that will be secret in combat for later use.
local function captureTargetSnapshot()
    -- Don't bother if the target isn't a mob.
    if UnitAffectingCombat("player") or not UnitExists("target")
        or UnitIsPlayer("target") or UnitPlayerControlled("target")
    then
        return
    end

    -- Try to grab the guid. Will not succeed in combat.
    local guid = UnitGUID("target")
    if not guid then
        return
    end

    -- Translate the GUID to creature data that we can match against the damage meter entries.
    local creatureID = C_CreatureInfo.GetCreatureID(guid)
    local level = UnitLevel("target")
    local classification = UnitClassification("target")
    local zone = GetRealZoneText()
    local powerType = UnitPowerType("target")
    if creatureID <= 0 or level <= 0 then
        return
    end

    targetSnapshots[guid] = {
        creatureID = creatureID,
        zone = zone,
        level = level,
        classification = classification,
        powerType = powerType,
    }
end

-- Estimate mob health from a completed Damage Meter session and update the cache.
local function cacheCombatSession(combatSession)
    if not combatSession then
        return
    end

    local combatSources = combatSession.combatSources
    if issecretvalue(combatSources) then
        return
    end

    local snapshots = targetSnapshots
    -- There were multiple mob types involved. We cannot get a reliable damage estimate for a single mob, so abort.
    if #combatSources ~= 1 then
        targetSnapshots = {}
        return
    end

    -- Get the data for the one type we killed. If it's not secret then combat is over and we can continue.
    local source = combatSources[1]
    local creatureID = scrubsecretvalues(source.sourceCreatureID)
    if not creatureID then
        return
    end

    -- Look through the target snapshots to try to find something matching the mob in our segment row.
    local classification = source.classification
    local zone = GetRealZoneText()
    local estimate = combatSession.totalAmount
    local snapshot
    local ambiguous = false

    if not issecretvalue(estimate) and estimate and estimate > 0 then
        -- Reduce the health estimate by an estimate of our overkill damage to reflect expected max health.
        estimate = estimate - estimateOverkillDamage(UnitLevel("Player"))

        -- Try to find a recent targeted mob with the exact same creature ID. If we have targeted multiple mobs with
        -- the same ID then only accept it as the type we killed if they all have the same level. Otherwise, treat the
        -- data is ambiguous.
        for _, targetSnapshot in pairs(snapshots) do
            if targetSnapshot.creatureID == creatureID and targetSnapshot.zone == zone
                and targetSnapshot.classification == classification
            then
                if snapshot and (targetSnapshot.level ~= snapshot.level) then
                    ambiguous = true
                    break
                end
                snapshot = targetSnapshot
            end
        end

        -- We have recently targeted a mob that matches the damage meter entry unambiguously. Assume this is the same
        -- mob and update the cached averages with its estimated health.
        if snapshot and not ambiguous then
            updateHealthCaches(
                SunderedMobHealthCache, snapshot.level, classification, snapshot.powerType, zone, estimate
            )
        end
    end

    -- Discard target snapshots for this mob type for future use.
    for guid, snapshot in pairs(targetSnapshots) do
        if snapshot.creatureID == creatureID then
            targetSnapshots[guid] = nil
        end
    end
end

-- Grab the damage taken session from the in-game damage meter and send it to the cache update function.
local function readCombatSession(sessionID)
    local isAvailable = C_DamageMeter.IsDamageMeterAvailable()
    if not isAvailable then
        return
    end

    local damageMeterType = Enum.DamageMeterType.EnemyDamageTaken
    local combatSession
    if sessionID then
        combatSession = C_DamageMeter.GetCombatSessionFromID(sessionID, damageMeterType)
    else
        local currentSession = Enum.DamageMeterSessionType.Current
        combatSession = C_DamageMeter.GetCombatSessionFromType(currentSession, damageMeterType)
    end

    cacheCombatSession(combatSession)
end

-- Handler for the PLAYER_TARGET_CHANGED and PLAYER_ENTERING_WORLD event
function mobHealthCache:OnPlayerTargetChanged()
    captureTargetSnapshot()
end

-- Handler for the DAMAGE_METER_COMBAT_SESSION_UPDATED event.
-- I am unsure if this is actually needed, since we read the data on combat end.
function mobHealthCache:OnDamageMeterCombatSessionUpdated(event, damageMeterType, sessionID)
    if damageMeterType ~= Enum.DamageMeterType.EnemyDamageTaken or sessionID == 0 then
        return
    end

    readCombatSession(sessionID)
end

-- Handler for the PLAYER_REGEN_ENABLED. This indicates combat has ended.
function mobHealthCache:OnPlayerRegenEnabled()
    readCombatSession()
end

-- Starts listening for combat meter updates and combat end.
function mobHealthCache:OnEnable()
    self:RegisterEvent("PLAYER_TARGET_CHANGED", "OnPlayerTargetChanged")
    self:RegisterEvent("PLAYER_ENTERING_WORLD", "OnPlayerTargetChanged")
    self:RegisterEvent("DAMAGE_METER_COMBAT_SESSION_UPDATED", "OnDamageMeterCombatSessionUpdated")
    self:RegisterEvent("PLAYER_REGEN_ENABLED", "OnPlayerRegenEnabled")
    captureTargetSnapshot()
end

-- Stops listening for combat meter updates and combat end.
function mobHealthCache:OnDisable()
    self:UnregisterEvent("PLAYER_TARGET_CHANGED")
    self:UnregisterEvent("PLAYER_ENTERING_WORLD")
    self:UnregisterEvent("DAMAGE_METER_COMBAT_SESSION_UPDATED")
    self:UnregisterEvent("PLAYER_REGEN_ENABLED")
end

-- Estimates target maximum health from its level and classification.
function mobHealthCache:EstimateTargetMaxHealth()
    ensureHealthCache()

    local zone = GetRealZoneText()
    local level = UnitLevel("target")
    local classification = UnitClassification("target")
    local powerType = UnitPowerType("target")

    -- Traverse the cache hierarchy, starting with the most specific: (level/classification/power type/zone)
    local levelCache = SunderedMobHealthCache.byLevelClassificationPowerTypeZone[level]
    local classificationCache = levelCache and levelCache[classification]
    local powerTypeCache = classificationCache and classificationCache[powerType]
    local cachedHealth = powerTypeCache and powerTypeCache[zone]
    if cachedHealth then
        return cachedHealth
    end

    -- Fall back to the next most specific: (level/classification/power type)
    levelCache = SunderedMobHealthCache.byLevelClassificationPowerType[level]
    classificationCache = levelCache and levelCache[classification]
    cachedHealth = classificationCache and classificationCache[powerType]
    if cachedHealth then
        return cachedHealth
    end

    -- Fall back to the next most specific: (level/classification)
    levelCache = SunderedMobHealthCache.byLevelClassification[level]
    cachedHealth = levelCache and levelCache[classification]
    if cachedHealth then
        return cachedHealth
    end

    -- Fall back to scaling up the normal mob health estimate by our approximate factor.
    if classification ~= "normal" then
        levelCache = SunderedMobHealthCache.byLevelClassification[level]
        local normalHealth = levelCache and levelCache.normal
        if normalHealth then
            return normalHealth * approximateHealthMultiplierByClassification[classification]
        end
    end

    -- No remotely relevant value in the cache. Use hardcoded table of global estimates.
    level = math.max(1, math.min(level, 63))
    local baseHealth = approximateMaxHealthByLevel[level]
    local multiplier = approximateHealthMultiplierByClassification[classification]
    return baseHealth * multiplier
end
